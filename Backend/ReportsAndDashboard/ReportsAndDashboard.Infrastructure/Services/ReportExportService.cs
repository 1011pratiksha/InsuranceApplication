
using ClosedXML.Excel;
using DocumentFormat.OpenXml.InkML;
using InsuranceApp.Infrastructure.Persistence;
using Microsoft.EntityFrameworkCore;
using QuestPDF.Fluent;
using ReportsAndDashboard.Application.Interfaces;
using ReportsAndDashboard.Domain.Entities.Reporting;
using System;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace ReportsAndDashboard.Infrastructure.Services
{
  public class ReportExportService : IReportExportService
  {
    private readonly AppDbContext db;

    // Existing report_master record ID.
    // Replace if the valid report ID is different.
    private const long ExportReportId = 1;

    public ReportExportService(AppDbContext db)
    {
      this.db = db;
    }

    public async Task<byte[]> ExportCsvAsync()
    {
      var snapshots = await db.AnalyticsSnapshots
          .AsNoTracking()
          .OrderByDescending(x => x.SnapshotDate)
          .ToListAsync();

      var csv = new StringBuilder();
      csv.AppendLine(
          "SnapshotId,SnapshotDate,TotalCustomers,TotalPolicies,PremiumCollected,ClaimsPaid,Revenue");

      foreach (var item in snapshots)
      {
        csv.AppendLine(string.Join(",",
            item.SnapshotId.ToString(CultureInfo.InvariantCulture),
            EscapeCsv(item.SnapshotDate.ToString(
                "yyyy-MM-dd", CultureInfo.InvariantCulture)),
            item.TotalCustomers.ToString(CultureInfo.InvariantCulture),
            item.TotalPolicies.ToString(CultureInfo.InvariantCulture),
            item.PremiumCollected.ToString(CultureInfo.InvariantCulture),
            item.ClaimsPaid.ToString(CultureInfo.InvariantCulture),
            item.Revenue.ToString(CultureInfo.InvariantCulture)
        ));
      }

      var content = Encoding.UTF8.GetPreamble()
          .Concat(Encoding.UTF8.GetBytes(csv.ToString()))
          .ToArray();

      await LogExportAsync("dashboard-analytics.csv");
      return content;
    }

    public async Task<byte[]> ExportPdfAsync()
    {
      var snapshots = await db.AnalyticsSnapshots
          .AsNoTracking()
          .OrderByDescending(x => x.SnapshotDate)
          .ToListAsync();

      QuestPDF.Settings.License =
          QuestPDF.Infrastructure.LicenseType.Community;

      var document = QuestPDF.Fluent.Document.Create(container =>
      {
        container.Page(page =>
        {
          page.Size(QuestPDF.Helpers.PageSizes.A4);
          page.Margin(30);
          page.DefaultTextStyle(x => x.FontSize(10));

          page.Header()
              .Text("Dashboard Analytics Report")
              .Bold()
              .FontSize(18);

          page.Content().PaddingTop(15).Table(table =>
          {
            table.ColumnsDefinition(columns =>
            {
              columns.RelativeColumn();
              columns.RelativeColumn();
              columns.RelativeColumn();
              columns.RelativeColumn();
              columns.RelativeColumn();
            });

            table.Header(header =>
            {
              header.Cell().Element(CellStyle).Text("Date");
              header.Cell().Element(CellStyle).Text("Customers");
              header.Cell().Element(CellStyle).Text("Policies");
              header.Cell().Element(CellStyle).Text("Premium");
              header.Cell().Element(CellStyle).Text("Revenue");
            });

            foreach (var item in snapshots)
            {
              table.Cell().Element(CellStyle)
                  .Text(item.SnapshotDate.ToString("yyyy-MM-dd"));
              table.Cell().Element(CellStyle)
                  .Text(item.TotalCustomers.ToString());
              table.Cell().Element(CellStyle)
                  .Text(item.TotalPolicies.ToString());
              table.Cell().Element(CellStyle)
                  .Text(item.PremiumCollected.ToString("N2"));
              table.Cell().Element(CellStyle)
                  .Text(item.Revenue.ToString("N2"));
            }
          });

          page.Footer().AlignCenter().Text(text =>
          {
            text.Span("Generated by Insurance Reports API");
          });
        });
      });

      var content = document.GeneratePdf();
      await LogExportAsync("dashboard-analytics.pdf");
      return content;
    }

    public async Task<byte[]> ExportExcelAsync()
    {
      var snapshots = await db.AnalyticsSnapshots
          .AsNoTracking()
          .OrderByDescending(x => x.SnapshotDate)
          .ToListAsync();

      using var workbook = new XLWorkbook();
      var worksheet = workbook.Worksheets.Add("Dashboard Analytics");

      worksheet.Cell(1, 1).Value = "Snapshot ID";
      worksheet.Cell(1, 2).Value = "Snapshot Date";
      worksheet.Cell(1, 3).Value = "Total Customers";
      worksheet.Cell(1, 4).Value = "Total Policies";
      worksheet.Cell(1, 5).Value = "Premium Collected";
      worksheet.Cell(1, 6).Value = "Claims Paid";
      worksheet.Cell(1, 7).Value = "Revenue";

      var header = worksheet.Range(1, 1, 1, 7);
      header.Style.Font.Bold = true;
      header.Style.Fill.BackgroundColor = XLColor.LightBlue;

      var row = 2;
      foreach (var item in snapshots)
      {
        worksheet.Cell(row, 1).Value = item.SnapshotId;
        worksheet.Cell(row, 2).Value = item.SnapshotDate;
        worksheet.Cell(row, 2).Style.DateFormat.Format = "yyyy-MM-dd";
        worksheet.Cell(row, 3).Value = item.TotalCustomers;
        worksheet.Cell(row, 4).Value = item.TotalPolicies;
        worksheet.Cell(row, 5).Value = item.PremiumCollected;
        worksheet.Cell(row, 6).Value = item.ClaimsPaid;
        worksheet.Cell(row, 7).Value = item.Revenue;
        row++;
      }

      worksheet.Columns().AdjustToContents();

      using var stream = new MemoryStream();
      workbook.SaveAs(stream);

      var content = stream.ToArray();
      await LogExportAsync("dashboard-analytics.xlsx");
      return content;
    }

    private async Task LogExportAsync(string fileName)
    {
      var reportExists = await db.Set<ReportMaster>()
          .AnyAsync(x => x.ReportId == ExportReportId);

      if (!reportExists)
      {
        throw new InvalidOperationException(
            $"Cannot log export: report_master ID {ExportReportId} does not exist.");
      }

      var execution = new ReportExecution
      {
        ReportId = ExportReportId,
        ExecutedBy = null,
        ExecutionDate = DateTime.UtcNow,
        ExecutionStatus = ReportExecutionStatus.Success,
        FilePath = fileName
      };

      db.ReportExecutions.Add(execution);
      await db.SaveChangesAsync();
    }

    private static string EscapeCsv(string value)
    {
      if (value.Contains(',') ||
          value.Contains('"') ||
          value.Contains('\n') ||
          value.Contains('\r'))
      {
        return "\"" + value.Replace("\"", "\"\"") + "\"";
      }

      return value;
    }

    private static QuestPDF.Infrastructure.IContainer CellStyle(
        QuestPDF.Infrastructure.IContainer container)
    {
      return container
          .Border(1)
          .BorderColor(QuestPDF.Helpers.Colors.Grey.Lighten2)
          .Padding(5);
    }

    public async Task<List<ReportExecution>> GetExportHistoryAsync()
    {
      return await db.ReportExecutions
          .AsNoTracking()
          .OrderByDescending(x => x.ExecutionDate)
          .ToListAsync();
    }
  }
}
